const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/connection.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const target = { exports: {} };
new Function('module', 'exports', compiled)(target, target.exports);
const { envValue, laravelConfig } = target.exports;
assert.equal(envValue('fixture-password'), 'fixture-password');
assert.equal(envValue('developer@mailgrid.test'), 'developer@mailgrid.test');
assert.equal(envValue('a$#"\\ pass'), String.raw`"a\$#\"\\ pass"`);
assert.equal(envValue('null'), String.raw`"\"null\""`);
assert.equal(envValue('(true)'), String.raw`"\"(true)\""`);
assert.equal(envValue('"quoted"'), String.raw`"\"\"quoted\"\""`);
const config = laravelConfig('developer@mailgrid.test', 'fixture-password', { smtp: 2525, imap: 1143, pop3: 1110 });
assert(config.includes('MAIL_PORT=2525\n'));
assert(config.includes('MAIL_PASSWORD=fixture-password\n'));
assert(config.includes('MAIL_FROM_NAME="${APP_NAME}"'));
assert.equal(config.split('\n').length, 8);
console.log('PASS: Laravel config ports, credentials, literal special characters, reserved words');
